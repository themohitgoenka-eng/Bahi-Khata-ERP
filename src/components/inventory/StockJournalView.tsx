import React, { useState, useEffect } from 'react';
import { useApp } from '../../context/AppContext';
import { inventoryEngine } from '../../services/inventoryEngine';
import { ExportEngine } from '../../services/exportEngine';
import { StockJournalEntry, StockJournalType } from '../../types';
import { StockJournalModal } from './StockJournalModal';
import { StockJournalPrintModal } from './StockJournalPrintModal';
import { ConfirmationModal, ConfirmationType } from '../common/ConfirmationModal';
import { formatDateDisplay } from '../../utils/dateUtils';
import { PdfFileIcon, ExcelFileIcon } from '../common/DocumentIcons';
import { useTableKeyboardNavigation } from '../../hooks/useTableKeyboardNavigation';
import {
  Layers,
  Plus,
  FileDown,
  Printer,
  Search,
  ArrowRight,
  ArrowRightLeft,
  Trash2,
  Edit2,
  Calendar,
  Filter,
  CheckCircle2,
  TrendingUp,
  Package,
} from 'lucide-react';

export const StockJournalView: React.FC = () => {
  const { currentCompany, currentFiscalYear, showNotification, refreshActiveData } = useApp();

  const [journals, setJournals] = useState<StockJournalEntry[]>([]);
  const [loading, setLoading] = useState<boolean>(true);
  const [searchTerm, setSearchTerm] = useState<string>('');
  const [filterType, setFilterType] = useState<StockJournalType | 'ALL'>('ALL');

  // Modals
  const [modalOpen, setModalOpen] = useState<boolean>(false);
  const [editingJournal, setEditingJournal] = useState<StockJournalEntry | null>(null);
  const [printJournal, setPrintJournal] = useState<StockJournalEntry | null>(null);

  // Confirmation Modal
  const [confirmModal, setConfirmModal] = useState<{
    isOpen: boolean;
    type: ConfirmationType;
    title: string;
    message: string;
    details?: { label: string; value: string | number }[];
    onConfirm: () => void;
  }>({
    isOpen: false,
    type: 'INFO',
    title: '',
    message: '',
    onConfirm: () => {},
  });

  const loadStockJournals = async () => {
    setLoading(true);
    try {
      const data = await inventoryEngine.getStockJournals();
      setJournals(data || []);
    } catch (err: any) {
      console.warn('Stock journal load fallback:', err);
      setJournals([]);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadStockJournals();
  }, [currentCompany, currentFiscalYear]);

  const filteredJournals = journals.filter((j) => {
    const term = searchTerm.toLowerCase().trim();
    const matchesSearch =
      !term ||
      j.voucherNo.toLowerCase().includes(term) ||
      (j.referenceNo && j.referenceNo.toLowerCase().includes(term)) ||
      (j.narration && j.narration.toLowerCase().includes(term)) ||
      (j.sourceItems || []).some((s) => s.itemName.toLowerCase().includes(term) || s.itemCode.toLowerCase().includes(term)) ||
      (j.destinationItems || []).some((d) => d.itemName.toLowerCase().includes(term) || d.itemCode.toLowerCase().includes(term));

    const matchesType = filterType === 'ALL' || j.journalType === filterType;
    return matchesSearch && matchesType;
  });

  const totalSourceValue = filteredJournals.reduce((s, j) => s + (j.totalSourceAmount || 0), 0);
  const totalDestValue = filteredJournals.reduce((s, j) => s + (j.totalDestinationAmount || 0), 0);
  const totalOverheads = filteredJournals.reduce((s, j) => s + (j.additionalCost || 0), 0);

  // Keyboard navigation for Stock Journal table
  const { selectedIndex, setSelectedIndex } = useTableKeyboardNavigation({
    totalRows: filteredJournals.length,
    tableId: 'stock-journal-table',
    enabled: !modalOpen && !editingJournal && !printJournal && !confirmModal.isOpen,
  });

  const handleDeleteJournal = (journal: StockJournalEntry) => {
    setConfirmModal({
      isOpen: true,
      type: 'DELETE',
      title: 'Confirm Delete Stock Journal',
      message: `Are you sure you want to delete stock journal voucher "${journal.voucherNo}"? All stock movements generated by this voucher will be reversed.`,
      details: [
        { label: 'Voucher No', value: journal.voucherNo },
        { label: 'Date', value: formatDateDisplay(journal.date) },
        { label: 'Type', value: journal.journalType },
        { label: 'Consumed Value', value: `₹${journal.totalSourceAmount.toFixed(2)}` },
        { label: 'Output Value', value: `₹${journal.totalDestinationAmount.toFixed(2)}` },
      ],
      onConfirm: async () => {
        setConfirmModal((prev) => ({ ...prev, isOpen: false }));
        try {
          await inventoryEngine.deleteStockJournal(journal.id);
          showNotification(`Stock journal "${journal.voucherNo}" deleted and stock reversed.`, 'info');
          await loadStockJournals();
          await refreshActiveData();
        } catch (err: any) {
          showNotification(err.message || 'Failed to delete stock journal.', 'error');
        }
      },
    });
  };

  const handleExportPdf = () => {
    if (!currentCompany || !currentFiscalYear) return;
    if (filteredJournals.length === 0) {
      showNotification('No stock journal entries to export.', 'info');
      return;
    }

    const columns = [
      { header: 'Voucher No', dataKey: 'voucherNo', width: 25 },
      { header: 'Date', dataKey: 'date', width: 22 },
      { header: 'Journal Type', dataKey: 'type', width: 28 },
      { header: 'Source (Consumed)', dataKey: 'source', width: 45 },
      { header: 'Destination (Output)', dataKey: 'destination', width: 45 },
      { header: 'Overheads (₹)', dataKey: 'overhead', width: 20, align: 'right' as const },
      { header: 'Total Value (₹)', dataKey: 'total', width: 25, align: 'right' as const },
    ];

    const data = filteredJournals.map((j) => ({
      voucherNo: j.voucherNo,
      date: formatDateDisplay(j.date),
      type: j.journalType.replace('_', ' '),
      source: j.sourceItems.map((s) => `${s.itemName} (${s.quantity} ${s.unit})`).join(', '),
      destination: j.destinationItems.map((d) => `${d.itemName} (${d.quantity} ${d.unit})`).join(', '),
      overhead: j.additionalCost ? `₹${j.additionalCost.toFixed(2)}` : '₹0.00',
      total: `₹${j.totalDestinationAmount.toFixed(2)}`,
    }));

    ExportEngine.exportToPdf({
      company: currentCompany,
      fiscalYear: currentFiscalYear,
      reportTitle: 'Stock Journal & Manufacturing Register',
      columns,
      data,
      summaryRows: [
        {
          voucherNo: 'TOTALS',
          date: '',
          type: `${filteredJournals.length} Vouchers`,
          source: '',
          destination: '',
          overhead: `₹${totalOverheads.toFixed(2)}`,
          total: `₹${totalDestValue.toFixed(2)}`,
        },
      ],
      filenamePrefix: 'stock_journal_register',
    });
  };

  const handleExportCsv = () => {
    if (!currentCompany || !currentFiscalYear) return;
    if (filteredJournals.length === 0) {
      showNotification('No stock journal entries to export.', 'info');
      return;
    }

    const columns = [
      { header: 'Voucher No', dataKey: 'voucherNo' },
      { header: 'Date', dataKey: 'date' },
      { header: 'Journal Type', dataKey: 'type' },
      { header: 'Source Items', dataKey: 'source' },
      { header: 'Destination Items', dataKey: 'destination' },
      { header: 'Additional Cost', dataKey: 'overhead' },
      { header: 'Total Destination Value', dataKey: 'total' },
      { header: 'Narration', dataKey: 'narration' },
    ];

    const data = filteredJournals.map((j) => ({
      voucherNo: j.voucherNo,
      date: j.date,
      type: j.journalType,
      source: j.sourceItems.map((s) => `${s.itemName}: ${s.quantity} ${s.unit}`).join('; '),
      destination: j.destinationItems.map((d) => `${d.itemName}: ${d.quantity} ${d.unit}`).join('; '),
      overhead: (j.additionalCost || 0).toString(),
      total: (j.totalDestinationAmount || 0).toString(),
      narration: j.narration || '',
    }));

    ExportEngine.exportToExcel({
      company: currentCompany,
      fiscalYear: currentFiscalYear,
      reportTitle: 'Stock Journal & Manufacturing Register',
      columns,
      data,
      filenamePrefix: 'stock_journal_register',
    });
  };

  const getJournalTypeBadge = (t: StockJournalType) => {
    switch (t) {
      case 'MANUFACTURING':
        return (
          <span className="px-2 py-0.5 rounded-lg text-[10px] font-semibold bg-[rgba(57,167,255,0.18)] text-[#2588E8] border border-[rgba(112,185,245,0.25)]">
            Manufacturing
          </span>
        );
      case 'INTER_LOCATION':
        return (
          <span className="px-2 py-0.5 rounded-lg text-[10px] font-semibold bg-[rgba(100,160,200,0.15)] text-[#a5d8f0] border border-[rgba(100,160,200,0.25)]">
            Godown Transfer
          </span>
        );
      case 'CONSUMPTION_PRODUCTION':
        return (
          <span className="px-2 py-0.5 rounded-lg text-[10px] font-semibold bg-[rgba(180,140,220,0.15)] text-[#d8b4fe] border border-[rgba(180,140,220,0.25)]">
            Consumption &amp; Prod
          </span>
        );
      case 'STOCK_ADJUSTMENT':
        return (
          <span className="px-2 py-0.5 rounded-lg text-[10px] font-semibold bg-[rgba(57,167,255,0.15)] text-[#2588E8] border border-[rgba(112,185,245,0.25)]">
            Repacking / Conv
          </span>
        );
      default:
        return (
          <span className="px-2 py-0.5 rounded-lg text-[10px] font-semibold bg-[rgba(18,48,76,0.48)] backdrop-blur-xl text-[#B7C9D9] border border-[rgba(112,185,245,0.25)]">
            Transfer
          </span>
        );
    }
  };

  return (
    <div className="space-y-2" id="stock_journal_view">
      {/* Header Bar */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-2 bg-[rgba(13,38,62,0.48)] backdrop-blur-xl px-3.5 py-2 rounded-xl border border-[rgba(112,185,245,0.25)] shadow-md">
        <div className="flex items-center gap-2.5">
          <div className="p-1.5 rounded-lg bg-[rgba(57,167,255,0.15)] border border-[rgba(112,185,245,0.25)] flex items-center justify-center text-[#2588E8] shadow-xs">
            <Layers className="w-4 h-4" />
          </div>
          <div>
            <h1 className="text-sm font-bold text-[#FFFFFF] tracking-wide">
              STOCK JOURNAL REGISTER
            </h1>
            <p className="text-[10.5px] text-[#7F98AE] hidden sm:block">
              Record material consumption, manufacturing transformation, finished goods production &amp; inter-godown transfers.
            </p>
          </div>
        </div>

        <div className="flex flex-wrap items-center gap-1.5">
          <button
            onClick={handleExportPdf}
            className="flex items-center gap-1.5 bg-[rgba(18,48,76,0.48)] hover:bg-[rgba(57,167,255,0.15)] text-[#B7C9D9] hover:text-[#FFFFFF] px-2.5 py-1 rounded-lg border border-[rgba(112,185,245,0.25)] text-xs font-semibold transition cursor-pointer"
          >
            <PdfFileIcon className="w-3.5 h-3.5" />
            Export PDF
          </button>
          <button
            onClick={handleExportCsv}
            className="flex items-center gap-1.5 bg-[rgba(18,48,76,0.48)] hover:bg-[rgba(57,167,255,0.15)] text-[#B7C9D9] hover:text-[#FFFFFF] px-2.5 py-1 rounded-lg border border-[rgba(112,185,245,0.25)] text-xs font-semibold transition cursor-pointer"
          >
            <ExcelFileIcon className="w-3.5 h-3.5" />
            Export Excel
          </button>
          <button
            onClick={() => {
              setEditingJournal(null);
              setModalOpen(true);
            }}
            className="flex items-center gap-1 bg-[#2588E8] hover:bg-[#39A7FF] text-[#FFFFFF] font-bold px-3 py-1 rounded-lg text-xs transition shadow-sm cursor-pointer"
          >
            <Plus className="w-3.5 h-3.5" />
            New Stock Journal (Alt+J)
          </button>
        </div>
      </div>

      {/* KPI Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-2 text-xs">
        <div className="bg-[rgba(13,38,62,0.48)] backdrop-blur-xl border border-[rgba(112,185,245,0.25)] rounded-xl px-3 py-1.5 shadow-sm flex items-center justify-between">
          <div>
            <div className="text-[10px] text-[#7F98AE] font-semibold">Total Stock Journals</div>
            <div className="text-base font-bold font-mono text-[#FFFFFF]">{filteredJournals.length}</div>
          </div>
          <Layers className="w-3.5 h-3.5 text-[#2588E8]" />
        </div>

        <div className="bg-[rgba(13,38,62,0.48)] backdrop-blur-xl border border-[rgba(112,185,245,0.25)] rounded-xl px-3 py-1.5 shadow-sm flex items-center justify-between">
          <div>
            <div className="text-[10px] text-[#7F98AE] font-semibold">Material Consumed</div>
            <div className="text-base font-bold font-mono text-[#fca5a5]">
              ₹{totalSourceValue.toLocaleString('en-IN', { minimumFractionDigits: 2 })}
            </div>
          </div>
          <Package className="w-3.5 h-3.5 text-[#fca5a5]" />
        </div>

        <div className="bg-[rgba(13,38,62,0.48)] backdrop-blur-xl border border-[rgba(112,185,245,0.25)] rounded-xl px-3 py-1.5 shadow-sm flex items-center justify-between">
          <div>
            <div className="text-[10px] text-[#7F98AE] font-semibold">Finished Production</div>
            <div className="text-base font-bold font-mono text-[#2588E8]">
              ₹{totalDestValue.toLocaleString('en-IN', { minimumFractionDigits: 2 })}
            </div>
          </div>
          <TrendingUp className="w-3.5 h-3.5 text-[#2588E8]" />
        </div>

        <div className="bg-[rgba(13,38,62,0.48)] backdrop-blur-xl border border-[rgba(112,185,245,0.25)] rounded-xl px-3 py-1.5 shadow-sm flex items-center justify-between">
          <div>
            <div className="text-[10px] text-[#7F98AE] font-semibold">Overheads &amp; Processing</div>
            <div className="text-base font-bold font-mono text-[#2588E8]">
              ₹{totalOverheads.toLocaleString('en-IN', { minimumFractionDigits: 2 })}
            </div>
          </div>
          <CheckCircle2 className="w-3.5 h-3.5 text-[#2588E8]" />
        </div>
      </div>

      {/* Filter and Search Bar */}
      <div className="bg-[rgba(13,38,62,0.48)] backdrop-blur-xl px-3 py-1.5 rounded-xl border border-[rgba(112,185,245,0.25)] flex flex-col md:flex-row gap-2 items-center justify-between text-xs shadow-sm">
        <div className="relative w-full md:w-80">
          <Search className="w-3.5 h-3.5 absolute left-3 top-2 text-[#7F98AE]" />
          <input
            type="text"
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            placeholder="Search by voucher no, item name, godown..."
            className="w-full bg-[rgba(18,48,76,0.48)] backdrop-blur-xl border border-[rgba(112,185,245,0.25)] rounded-xl pl-9 pr-3.5 py-1 text-[#FFFFFF] placeholder-[#7F98AE] focus:outline-hidden focus:border-[#2588E8]"
          />
        </div>

        <div className="flex items-center gap-2 w-full md:w-auto">
          <Filter className="w-3.5 h-3.5 text-[#7F98AE]" />
          <select
            value={filterType}
            onChange={(e) => setFilterType(e.target.value as any)}
            className="bg-[rgba(18,48,76,0.48)] border border-[rgba(112,185,245,0.25)] rounded-xl px-2.5 py-1 text-[#FFFFFF] text-xs focus:outline-hidden focus:border-[#2588E8]"
          >
            <option value="ALL" className="bg-[rgba(18,48,76,0.48)] backdrop-blur-xl text-[#FFFFFF]">All Journal Types</option>
            <option value="MANUFACTURING" className="bg-[rgba(18,48,76,0.48)] backdrop-blur-xl text-[#FFFFFF]">Manufacturing / Processing</option>
            <option value="INTER_LOCATION" className="bg-[rgba(18,48,76,0.48)] backdrop-blur-xl text-[#FFFFFF]">Inter-Godown Transfer</option>
            <option value="CONSUMPTION_PRODUCTION" className="bg-[rgba(18,48,76,0.48)] backdrop-blur-xl text-[#FFFFFF]">Consumption &amp; Production</option>
            <option value="GENERAL_TRANSFER" className="bg-[rgba(18,48,76,0.48)] backdrop-blur-xl text-[#FFFFFF]">General Stock Transfer</option>
            <option value="STOCK_ADJUSTMENT" className="bg-[rgba(18,48,76,0.48)] backdrop-blur-xl text-[#FFFFFF]">Repacking / Conversion</option>
          </select>
        </div>
      </div>

      {/* Data Table */}
      <div className="bg-[rgba(13,38,62,0.48)] backdrop-blur-xl border border-[rgba(112,185,245,0.25)] rounded-2xl overflow-hidden shadow-lg">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs border-collapse">
            <thead>
              <tr className="bg-[rgba(18,48,76,0.48)] backdrop-blur-xl border-b border-[rgba(112,185,245,0.25)] text-[#7F98AE] font-semibold uppercase text-[10.5px] tracking-wider leading-tight">
                <th className="py-0.5 px-3.5">Voucher No</th>
                <th className="py-0.5 px-3.5">Date</th>
                <th className="py-0.5 px-3.5">Type</th>
                <th className="py-0.5 px-3.5">Source (Consumed / Issue)</th>
                <th className="py-0.5 px-3.5">Destination (Produced / Receipt)</th>
                <th className="py-0.5 px-3.5 text-right">Overheads (₹)</th>
                <th className="py-0.5 px-3.5 text-right font-bold text-[#2588E8]">Total Output (₹)</th>
                <th className="py-0.5 px-3.5 text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-[rgba(112,185,245,0.15)]/40">
              {loading ? (
                <tr>
                  <td colSpan={8} className="py-8 text-center text-[#7F98AE]">
                    Loading Stock Journals...
                  </td>
                </tr>
              ) : filteredJournals.length === 0 ? (
                <tr>
                  <td colSpan={8} className="py-8 text-center text-[#7F98AE]">
                    No stock journal vouchers recorded yet. Click "New Stock Journal" to create one.
                  </td>
                </tr>
              ) : (
                filteredJournals.map((j, idx) => {
                  const isSelected = idx === selectedIndex;
                  return (
                    <tr
                      key={j.id}
                      data-table-id="stock-journal-table"
                      data-row-idx={idx}
                      onClick={() => setSelectedIndex(idx)}
                      className={`transition cursor-pointer leading-tight ${
                        isSelected
                          ? 'bg-[#184271] ring-2 ring-inset ring-[#39A7FF] border-l-4 border-l-[#F2C94C] text-white shadow-md font-semibold'
                          : 'hover:bg-[rgba(18,48,76,0.42)] backdrop-blur-xl'
                      }`}
                    >
                    <td className="py-1 px-3 font-bold text-[#FFFFFF]">
                      <div className="flex items-center gap-1.5">
                        <span className="text-[#2588E8] font-mono text-xs">{j.voucherNo}</span>
                      </div>
                      {j.referenceNo && (
                        <div className="text-[10px] text-[#7F98AE]">Ref: {j.referenceNo}</div>
                      )}
                    </td>
                    <td className="py-1 px-3 text-[#B7C9D9] font-mono whitespace-nowrap text-xs">
                      {formatDateDisplay(j.date)}
                    </td>
                    <td className="py-1 px-3 whitespace-nowrap">
                      {getJournalTypeBadge(j.journalType)}
                    </td>
                    <td className="py-1 px-3 text-[#B7C9D9]">
                      <div className="space-y-0.5">
                        {j.sourceItems.slice(0, 2).map((s, i) => (
                          <div key={i} className="text-[10.5px] text-[#fca5a5] font-medium flex items-center gap-1">
                            <span className="text-[10px] text-[#7F98AE]">•</span>
                            <span>{s.itemName}</span>
                            <span className="text-[#FFFFFF] font-bold">({s.quantity} {s.unit})</span>
                            <span className="text-[10px] text-[#7F98AE] font-mono">@{s.rate}</span>
                          </div>
                        ))}
                        {j.sourceItems.length > 2 && (
                          <div className="text-[10px] text-[#7F98AE] italic">
                            +{j.sourceItems.length - 2} more consumed items...
                          </div>
                        )}
                        {j.sourceItems.length === 0 && (
                          <span className="text-[#7F98AE] italic text-[11px]">None</span>
                        )}
                      </div>
                    </td>
                    <td className="py-1 px-3 text-[#B7C9D9]">
                      <div className="space-y-0.5">
                        {j.destinationItems.slice(0, 2).map((d, i) => (
                          <div key={i} className="text-[10.5px] text-[#2588E8] font-medium flex items-center gap-1">
                            <span className="text-[10px] text-[#7F98AE]">•</span>
                            <span>{d.itemName}</span>
                            <span className="text-[#FFFFFF] font-bold">({d.quantity} {d.unit})</span>
                            <span className="text-[10px] text-[#7F98AE] font-mono">@{d.rate}</span>
                          </div>
                        ))}
                        {j.destinationItems.length > 2 && (
                          <div className="text-[10px] text-[#7F98AE] italic">
                            +{j.destinationItems.length - 2} more output items...
                          </div>
                        )}
                        {j.destinationItems.length === 0 && (
                          <span className="text-[#7F98AE] italic text-[11px]">None</span>
                        )}
                      </div>
                    </td>
                    <td className="py-1 px-3 text-right font-mono text-[#B7C9D9] text-xs">
                      {j.additionalCost ? `₹${Number(j.additionalCost).toFixed(2)}` : '₹0.00'}
                    </td>
                    <td className="py-1 px-3 text-right font-mono font-bold text-[#2588E8] text-xs">
                      ₹{Number(j.totalDestinationAmount).toLocaleString('en-IN', { minimumFractionDigits: 2 })}
                    </td>
                    <td className="py-1 px-3 text-right">
                      <div className="flex items-center justify-end gap-1.5">
                        <button
                          onClick={() => setPrintJournal(j)}
                          title="Print Stock Journal Voucher"
                          className="p-1.5 rounded-lg bg-[rgba(18,48,76,0.48)] backdrop-blur-xl hover:bg-[rgba(18,48,76,0.48)] backdrop-blur-xl text-[#7F98AE] hover:text-[#2588E8] border border-[rgba(112,185,245,0.25)] transition cursor-pointer"
                        >
                          <Printer className="w-3.5 h-3.5" />
                        </button>
                        <button
                          onClick={() => {
                            setEditingJournal(j);
                            setModalOpen(true);
                          }}
                          title="Edit Stock Journal"
                          className="p-1.5 rounded-lg bg-[rgba(18,48,76,0.48)] backdrop-blur-xl hover:bg-[rgba(18,48,76,0.48)] backdrop-blur-xl text-[#7F98AE] hover:text-[#2588E8] border border-[rgba(112,185,245,0.25)] transition cursor-pointer"
                        >
                          <Edit2 className="w-3.5 h-3.5" />
                        </button>
                        <button
                          onClick={() => handleDeleteJournal(j)}
                          title="Delete Stock Journal"
                          className="p-1.5 rounded-lg bg-[rgba(18,48,76,0.48)] backdrop-blur-xl hover:bg-[#421d23] text-[#7F98AE] hover:text-[#fca5a5] border border-[rgba(112,185,245,0.25)] hover:border-rose-800/40 transition cursor-pointer"
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    </td>
                  </tr>
                );
              })
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Stock Journal Modal (Add / Edit) */}
      {modalOpen && (
        <StockJournalModal
          isOpen={modalOpen}
          onClose={() => {
            setModalOpen(false);
            setEditingJournal(null);
          }}
          onSuccess={async () => {
            await loadStockJournals();
            await refreshActiveData();
          }}
          journalToEdit={editingJournal}
        />
      )}

      {/* Print Modal */}
      {printJournal && (
        <StockJournalPrintModal
          isOpen={Boolean(printJournal)}
          onClose={() => setPrintJournal(null)}
          journal={printJournal}
        />
      )}

      {/* Confirmation Modal */}
      <ConfirmationModal
        isOpen={confirmModal.isOpen}
        type={confirmModal.type}
        title={confirmModal.title}
        message={confirmModal.message}
        itemDetails={confirmModal.details}
        onConfirm={confirmModal.onConfirm}
        onCancel={() => setConfirmModal((prev) => ({ ...prev, isOpen: false }))}
      />
    </div>
  );
};
